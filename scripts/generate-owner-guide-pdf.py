#!/usr/bin/env python3
"""Генерация PDF-инструкции для владельцев (проверка приложения и админки)."""

from pathlib import Path

from fpdf import FPDF

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "Coffee-Exchange-instrukciya-dlya-vladelcev.pdf"
FONT = "/System/Library/Fonts/Supplemental/Arial Unicode.ttf"


class GuidePDF(FPDF):
    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("UI", size=8)
        self.set_text_color(120, 100, 85)
        self.cell(0, 8, "Coffee Exchange — инструкция для владельцев", align="R")
        self.ln(4)

    def footer(self):
        self.set_y(-12)
        self.set_font("UI", size=8)
        self.set_text_color(120, 100, 85)
        self.cell(0, 8, f"Страница {self.page_no()}", align="C")

    def h1(self, text: str):
        self.ln(4)
        self.set_x(self.l_margin)
        self.set_font("UI", "B", 16)
        self.set_text_color(47, 36, 28)
        self.multi_cell(self.epw, 9, text)
        self.ln(2)

    def h2(self, text: str):
        self.ln(2)
        self.set_x(self.l_margin)
        self.set_font("UI", "B", 12)
        self.set_text_color(226, 100, 2)
        self.multi_cell(self.epw, 7, text)
        self.ln(1)

    def body(self, text: str):
        self.set_x(self.l_margin)
        self.set_font("UI", size=10)
        self.set_text_color(47, 36, 28)
        self.multi_cell(self.epw, 5.5, text)
        self.ln(1)

    def bullet(self, text: str):
        self.set_x(self.l_margin)
        self.set_font("UI", size=10)
        self.set_text_color(47, 36, 28)
        self.multi_cell(self.epw, 5.5, f"- {text}")


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)

    pdf = GuidePDF()
    pdf.set_margins(18, 18, 18)
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_font("UI", "", FONT)
    pdf.add_font("UI", "B", FONT)
    pdf.add_page()

    pdf.h1("Coffee Exchange")
    pdf.set_x(pdf.l_margin)
    pdf.set_font("UI", size=11)
    pdf.multi_cell(
        pdf.epw,
        6,
        "Инструкция для владельцев и проверяющих\n"
        "Версия от 22.09.2026 — админка кофеен, карта в приложении, интеграция с сервером лояльности",
    )
    pdf.ln(4)

    pdf.h2("Зачем этот документ")
    pdf.body(
        "Мы подключили админку кофеен к рабочему серверу и обновили карту в приложении для гостей. "
        "Ваша задача — проверить, что кофейни настраиваются без технических знаний, "
        "на карте видны только опубликованные точки с координатами, а гости получают корректный адрес и график работы."
    )

    pdf.h2("Что нового добавлено в систему (краткий обзор)")
    pdf.bullet(
        "Раздел админки «Кофейни»: список точек, создание, редактирование, публикация в приложении."
    )
    pdf.bullet(
        "Удобный график работы по дням недели (пн-вс), без редактирования JSON."
    )
    pdf.bullet(
        "Подсказки адреса при вводе: выбор из списка автоматически заполняет координаты для карты."
    )
    pdf.bullet(
        "Предупреждения в админке: метка «Нет на карте», если не указаны координаты; «Черновик», если точка не опубликована."
    )
    pdf.bullet(
        "Карта в приложении загружает кофейни с сервера; исправлено отображение координат и работа на сайте без ошибок доступа."
    )
    pdf.bullet(
        "Карта без размытия: подложка OpenStreetMap (раньше требовался ключ карт и появлялась надпись API key required)."
    )
    pdf.bullet(
        "Связанные разделы админки (если у вас есть доступ): аналитика, поддержка пользователей, контент меню, "
        "настройки правил, пользователи, купоны — подключены к API лояльности."
    )

    pdf.h2("1. Вход в админку")
    pdf.body("Откройте сайт Coffee Exchange и войдите под учётной записью администратора.")
    pdf.body("Перейдите в раздел «Кофейни» — там список всех точек сети.")
    pdf.body("Метки в списке:")
    pdf.bullet("«В приложении» — кофейня опубликована; гости могут её видеть (при наличии координат).")
    pdf.bullet("«Черновик» — в приложении не показывается, пока не включите «Показывать в приложении».")
    pdf.bullet("«Нет на карте» — нет широты/долготы; на карте метки не будет.")
    pdf.bullet("«Неактивна» — точка отключена в системе.")

    pdf.h2("2. Редактирование кофейни")
    pdf.body("Откройте нужную кофейню из списка.")
    pdf.body("Адрес: начните вводить текст — появятся подсказки. Обязательно выберите адрес из списка, "
             "а не только сохраните введённый текст. После выбора подсказки поля «Широта» и «Долгота» "
             "заполняются автоматически. Без координат кофейня не появится на карте.")
    pdf.body(
        "График работы: для каждого дня — галочка «Выходной» или время открытия и закрытия. "
        "Кнопка «Как в понедельнике — на все дни» копирует расписание понедельника на всю неделю."
    )
    pdf.body(
        "Публикация: галочка «Показывать в приложении (опубликована)» — без неё гости точку не увидят. "
        "«Активна» — обычно оставляют включённой."
    )
    pdf.body("Также можно заполнить название, описание, телефон, загрузить фото. Внизу нажмите «Сохранить».")

    pdf.h2("3. Карта в приложении (вид гостя)")
    pdf.body("В основном меню приложения откройте раздел «Карта».")
    pdf.body("Ожидаемое поведение: список кофеен и метки на чёткой карте; по нажатию на метку — карточка с адресом "
             "и статусом «Открыто» / «Закрыто» по графику работы.")
    pdf.body("Почему на карте может быть меньше точек, чем в админке:")
    pdf.bullet("кофейня в черновике (не опубликована);")
    pdf.bullet("нет координат (адрес не выбран из подсказок);")
    pdf.bullet("точка неактивна.")
    pdf.body(
        "На момент настройки: одна тестовая точка уже с координатами; для второй («Новая кофейня») "
        "нужно выбрать адрес из подсказок, включить публикацию и сохранить."
    )

    pdf.h2("4. Чек-лист проверки")
    pdf.body("Кофейни (админка):")
    pdf.bullet("открыть или создать кофейню;")
    pdf.bullet("ввести адрес и выбрать из подсказок;")
    pdf.bullet("проверить, что широта и долгота заполнились;")
    pdf.bullet("выставить график на неделю;")
    pdf.bullet("включить «Показывать в приложении»;")
    pdf.bullet("сохранить без ошибок.")
    pdf.body("Карта (приложение):")
    pdf.bullet("обновить страницу карты после сохранения;")
    pdf.bullet("увидеть кофейню в списке и на карте;")
    pdf.bullet("карта не размытая, без надписи про API key;")
    pdf.bullet("статус открыто/закрыто соответствует графику (на тестовой точке).")

    pdf.h2("5. Частые ситуации (не ошибка, а настройка)")
    pdf.bullet("В админке 2 кофейни, на карте 1 — у второй нет координат или черновик.")
    pdf.bullet("Ошибка при сохранении опубликованной точки — выберите адрес из подсказок или укажите координаты вручную.")
    pdf.bullet("Нет подсказок адреса — введите минимум 3–4 символа, подождите 1–2 секунды.")
    pdf.bullet("Карта не обновилась — обновите страницу (на компьютере: Cmd+Shift+R / Ctrl+F5).")

    pdf.h2("6. Что можно не проверять сейчас")
    pdf.bullet("Конструктор TV-меню для экранов в зале (отдельная задача).")
    pdf.bullet("Пустые или незавершённые разделы: достижения, массовые рассылки, модификаторы — если не обсуждалось отдельно.")
    pdf.bullet(
        "Тестовая кофейня с предзаказом и iiko: заказ может быть отклонён кассой — для служебной проверки это нормально."
    )

    pdf.h2("7. Как сообщать о проблемах")
    pdf.body("В одном сообщении укажите:")
    pdf.bullet("где проблема (админка / карта / другое);")
    pdf.bullet("шаги: что нажимали по порядку;")
    pdf.bullet("что ожидали и что получили;")
    pdf.bullet("скриншот и название кофейни;")
    pdf.bullet("по возможности: телефон и браузер (например, iPhone Safari).")

    pdf.h2("Кратко для чата")
    pdf.body(
        "В админке в «Кофейнях» настраиваем точку: адрес только из подсказок (тогда появится на карте), "
        "график — по дням недели, галочка «Показывать в приложении». В приложении на карте видны только "
        "опубликованные точки с координатами. Проверьте: сохранить → обновить карту → метка и карточка открываются, "
        "карта чёткая. Если что-то не так — скрин и шаги."
    )

    pdf.output(str(OUT))
    print(f"Written: {OUT}")


if __name__ == "__main__":
    main()
